// Optional browser check: requires Playwright and Chrome. Start `npm run dev` first.
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 const page=await browser.newPage({hasTouch:true})
 page.setDefaultTimeout(8000)
 page.on('pageerror',error=>console.error(error.message))
 await page.route('**/*.supabase.co/**',route=>route.request().url().includes('/storage/v1/object/') ? route.fulfill({status:200,contentType:'image/png',body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aZ1sAAAAASUVORK5CYII=','base64')}) : route.abort())
 await page.goto(`${process.env.SHADOW_TEST_URL || 'http://127.0.0.1:5173'}/tests/fixtures/shadow.html`)
 await page.getByRole('button',{name:'Shadow false'}).click()
 const first=page.locator('[data-message-id="one"] .shadow-message'), text=first.locator('p')
 const fake=await text.textContent()
 assert.ok(!fake.includes('Hidden'))
 await page.getByRole('button',{name:'Rerender'}).click()
 assert.equal(await text.textContent(),fake)
 await first.hover(); await page.mouse.down()
 assert.equal(await text.textContent(),'Hidden incoming secret')
 await page.mouse.up(); assert.equal(await text.textContent(),fake)
 const eye=first.getByRole('button',{name:'Hold to reveal message'})
 await eye.focus(); await page.keyboard.down('Space')
 assert.equal(await text.textContent(),'Hidden incoming secret')
 await page.keyboard.up('Space'); assert.equal(await text.textContent(),fake)
 const eyeBox=await eye.boundingBox(), touch={x:eyeBox.x+eyeBox.width/2,y:eyeBox.y+eyeBox.height/2}
 await page.touchscreen.tap(touch.x,touch.y)
 await page.waitForTimeout(300); assert.equal(await text.textContent(),fake)
 const cdp=await page.context().newCDPSession(page)
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch]})
 await page.waitForTimeout(300); assert.equal(await text.textContent(),'Hidden incoming secret')
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 assert.equal(await text.textContent(),fake)
 await eye.dispatchEvent('pointerdown',{button:0,pointerType:'mouse'})
 const second=page.locator('[data-message-id="two"] .shadow-message')
 await second.getByRole('button').dispatchEvent('pointerdown',{button:0,pointerType:'mouse'})
 assert.equal(await text.textContent(),fake)
 assert.equal(await second.locator('p').textContent(),'Hidden outgoing secret')
 await second.dispatchEvent('pointercancel'); assert.ok(!(await second.locator('p').textContent()).includes('Hidden'))
 for(const event of ['blur','scroll','visibilitychange']) {
   await eye.dispatchEvent('pointerdown',{button:0,pointerType:'mouse'})
   await page.evaluate(event=>window.dispatchEvent(new Event(event)),event)
   assert.equal(await text.textContent(),fake)
 }
 assert.equal(await first.evaluate(el=>getComputedStyle(el).userSelect),'none')
 assert.equal(await first.evaluate(el=>{const event=new Event('copy',{cancelable:true,bubbles:true});el.dispatchEvent(event);return event.defaultPrevented}),true)
 const picture=page.locator('.shadow-image img')
 await picture.waitFor()
 assert.equal(await picture.evaluate(el=>getComputedStyle(el).filter),'blur(22px)')
 const imageEye=page.locator('[data-message-id="image"]').getByRole('button',{name:'Hold to reveal message'})
 await imageEye.dispatchEvent('pointerdown',{button:0,pointerType:'mouse'})
 assert.equal(await picture.evaluate(el=>getComputedStyle(el).filter),'none')
 await imageEye.dispatchEvent('pointerup',{button:0,pointerType:'mouse'})
 assert.equal(await picture.evaluate(el=>getComputedStyle(el).filter),'blur(22px)')
 assert.equal(await page.getByRole('button',{name:'Open image preview'}).count(),0)
 assert.equal(await page.getByText('Download',{exact:true}).count(),0)
 await page.getByRole('button',{name:'Receive',exact:true}).click()
 assert.ok(!(await page.locator('[data-message-id="new"]').textContent()).includes('New incoming secret'))
 await page.getByRole('button',{name:'Switch conversation'}).click()
 assert.ok(!(await page.locator('[data-message-id="one"] p').textContent()).includes('Hidden'))
 await page.reload(); await page.getByRole('button',{name:'Shadow true'}).waitFor()
 await page.getByRole('button',{name:'Shadow true'}).click()
 await page.getByText('Hidden incoming secret',{exact:true}).waitFor()
 console.log('Passed mouse, touch, keyboard, cancellation, cache, incoming, copy, preview and persistence checks')
} finally {await browser.close()}
